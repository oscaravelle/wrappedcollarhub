#include <string>
#include <vector>

void vector_max() {
    std::vector<int> values;
    values.push_back(11);
    values.push_back(29);
    values.push_back(7);
    int best = values[0];
    for (std::size_t i = 1; i < values.size(); ++i) {
        if (values[i] > best) best = values[i];
    }
    (void)best;
}

void fibonacci_step() {
    int f0 = 0, f1 = 1;
    for (int i = 0; i < 10; ++i) {
        int next = f0 + f1;
        f0 = f1;
        f1 = next;
    }
    (void)f1;
}

void sort_small() {
    int values[4] = {9, 3, 7, 1};
    for (int i = 0; i < 4; ++i) {
        for (int j = i + 1; j < 4; ++j) {
            if (values[j] < values[i]) {
                int t = values[i];
                values[i] = values[j];
                values[j] = t;
            }
        }
    }
    (void)values[0];
}

void vector_reverse() {
    std::vector<int> values;
    values.push_back(1);
    values.push_back(2);
    values.push_back(3);
    std::vector<int> rev;
    for (std::size_t i = values.size(); i > 0; --i) rev.push_back(values[i - 1]);
    (void)rev;
}

extern "C" int silver_cove();
extern "C" void cobalt_thicket();
extern "C" void mellow_canyon();

int main() {
    vector_max();
    fibonacci_step();
    sort_small();
    vector_reverse();
    cobalt_thicket();
    mellow_canyon();
    return silver_cove();
}
